import assert from 'node:assert/strict';
import fs from 'node:fs';
import {patrolArrowImpact} from '../Hakkai_v7.1.0/BehaviorPack/scripts/mob_attack_visuals.js';
let marks=[];
const dimension={spawnParticle:(...args)=>marks.push(args)};
const arrow={typeId:'minecraft:arrow',location:{x:7,y:8,z:9},dimension};
const source={typeId:'hakkai:village_archer'};
const entity={location:{x:1,y:2,z:3}};
assert.equal(patrolArrowImpact({projectile:arrow,source,getEntityHit:()=>({entity})}),true);
assert.deepEqual(marks,[['hakkai:mob_impact',{x:1,y:2.6,z:3}]]);
marks=[];assert.equal(patrolArrowImpact({projectile:arrow,source}),true);
assert.deepEqual(marks,[['hakkai:mob_impact',{x:7,y:8,z:9}]],'block impact uses arrow location, not a new attack');
marks=[];for(const event of [null,{projectile:arrow},{projectile:arrow,source:{typeId:'minecraft:player'}},{projectile:{...arrow,typeId:'minecraft:snowball'},source},{source,projectile:{...arrow,location:{x:NaN,y:0,z:0}}}])assert.equal(patrolArrowImpact(event),false);
assert.equal(marks.length,0);
assert.equal(patrolArrowImpact({projectile:{...arrow,dimension:{spawnParticle(){throw Error('not loaded')}}},source}),false);
assert.equal(patrolArrowImpact({projectile:arrow,source,getEntityHit(){throw Error('no entity')}}),true,'entity lookup errors fall back to the projectile position');
const main=fs.readFileSync('Hakkai_v7.1.0/BehaviorPack/scripts/main.js','utf8');
assert.match(main,/safeSub\('world','after','projectileHitEntity',patrolArrowImpact\)/);
assert.match(main,/safeSub\('world','after','projectileHitBlock',patrolArrowImpact\)/);
assert.match(main,/projectileHitEntity',e=>\{/,'existing bow affinity callback is retained');
console.log('Patrol archer: native arrow entity/block impact visuals only, strict source and failure isolation (mocked)');
