#!/usr/bin/env python3
"""Derive automated recipes from existing, canonical crafting recipes."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1];recipes=root/'Hakkai_v7.1.0/BehaviorPack/recipes'
out=root/'Hakkai_v7.1.0/BehaviorPack/scripts/factory_line_recipes.js'
selections={
 'mixer':['mana_tonic','camp_stew','summer_corn_stew','spring_garden_soup','autumn_squash_potage','frost_blossom_tea','sunflower_trail_bowl','ice_tonic','spring_petals','sunflower_petals'],
 'assembler':['bandage','trail_ration','preserved_ration','camp_supply_pack','expedition_bento','forest_trail_meal','corn_bread','smoked_fish_strip','dried_sweet_berries','autumn_pie','spring_tulip_seed_save','summer_corn_seed_save','autumn_squash_seed_save','ice_blossom_seed_save','summer_sunflower_seed_save']
}
data={}
for kind,names in selections.items():
 data[kind]=[]
 for name in names:
  r=json.loads((recipes/f'{name}.json').read_text(encoding='utf8'))['minecraft:recipe_shapeless']
  counts={}
  for x in r['ingredients']:
   if set(x)!={'item'}:raise ValueError(f'non-item ingredient: {name}')
   counts[x['item']]=counts.get(x['item'],0)+1
  data[kind].append({'name':name,'costs':[{'id':k,'count':v} for k,v in counts.items()],'output':r['result']['item'],'amount':r['result'].get('count',1)})
recycle={}
for path in sorted(recipes.glob('recycle_drop_*.json')):
 r=json.loads(path.read_text(encoding='utf8'))['minecraft:recipe_shapeless'];i=r['ingredients'];o=r['result']
 if len(i)!=1 or set(i[0])!={'item'} or o.get('count',1)!=2:raise ValueError(path)
 recycle[i[0]['item']]=o['item']
out.write_text('// Generated by tools/build_factory_recipes.py from existing crafting recipes.\nexport const LINE_RECIPES='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\nexport const RECYCLE_DROPS='+json.dumps(recycle,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
print('line recipes',sum(map(len,data.values())),'mob materials',len(recycle))
